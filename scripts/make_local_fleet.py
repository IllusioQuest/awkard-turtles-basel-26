#!/usr/bin/env python3
"""Build a fleet house file for a local scenario: N houses on rings around a centre point, plus
optional named extra sites (pool, school, ...). Generic; one spec file per location (T-67).

    python3 scripts/make_local_fleet.py config/fleet/local/dreispitz.json

Spec format (every value needs an entry in spec["sources"]; example: config/fleet/local/dreispitz.json):
  centre {lat_deg, lon_deg}, rings_m [..], houses {count, prefix, <site fields>},
  defaults {<site fields shared by all sites>}, extra_sites [{house_id, <site fields>, annual_heat_kwh?}],
  outputs [{file, include_extra_sites, description}].
An extra site with annual_heat_kwh gets a flat demand: hot_water_kwh_per_day = annual / 365 and
design_heating_kw = 0 (the fleet has no per-site demand profile; the flat shape is stated as synthetic).

Deterministic: no random numbers. Positions are display only; physics uses each site's weather_ref.
"""
import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
METERS_PER_DEG_LAT = 111_320.0  # spherical-Earth approximation; positions are display only
DAYS_PER_YEAR = 365
FIELDS = ["house_id", "lat_deg", "lon_deg", "cell_id", "bfs_municipality_nr", "canton", "weather_ref",
          "design_heating_kw", "formula_divisor_c", "hot_water_kwh_per_day", "tank_kwh", "tank_initial_kwh",
          "electricity_price_chf_per_kwh", "server_count"]


def make_site(defaults, overrides, house_id, lat, lon):
    s = {**defaults, **overrides, "house_id": house_id, "lat_deg": round(lat, 6), "lon_deg": round(lon, 6)}
    if "annual_heat_kwh" in s:
        s["hot_water_kwh_per_day"] = round(s.pop("annual_heat_kwh") / DAYS_PER_YEAR, 3)
        s["design_heating_kw"] = 0
    missing = [f for f in FIELDS if f not in s]
    if missing:
        raise SystemExit(f"site {house_id}: missing fields {missing}")
    return {f: s[f] for f in FIELDS}


def ring_houses(spec):
    c, h = spec["centre"], dict(spec["houses"])
    count, prefix, rings = h.pop("count"), h.pop("prefix", "h"), spec["rings_m"]
    m_per_deg_lon = METERS_PER_DEG_LAT * math.cos(math.radians(c["lat_deg"]))
    out = []
    for i in range(count):
        angle, r = 2 * math.pi * i / count, rings[i % len(rings)]
        out.append(make_site(spec["defaults"], h, f"{prefix}{i + 1:03d}",
                             c["lat_deg"] + r * math.sin(angle) / METERS_PER_DEG_LAT,
                             c["lon_deg"] + r * math.cos(angle) / m_per_deg_lon))
    return out


def extra_sites(spec):
    c = spec["centre"]
    out = []
    for e in spec.get("extra_sites", []):
        e = dict(e)
        out.append(make_site(spec["defaults"], e, e.pop("house_id"),
                             e.pop("lat_deg", c["lat_deg"]), e.pop("lon_deg", c["lon_deg"])))
    return out


def main(spec_path):
    spec = json.loads(Path(spec_path).read_text(encoding="utf-8"))
    houses, extras = ring_houses(spec), extra_sites(spec)
    for o in spec["outputs"]:
        sites = houses + (extras if o.get("include_extra_sites") else [])
        doc = {"spec": {"description": o["description"] + f" Generated by scripts/make_local_fleet.py from {spec_path}.",
                        "sources": spec["sources"]},
               "seed": None, "houses": sites}
        path = ROOT / o["file"]
        path.write_text(json.dumps(doc, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        print(f"{len(sites)} sites -> {o['file']}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    main(sys.argv[1])
