#!/usr/bin/env python3
"""Write config/fleet/clients/canton-capitals.csv (fleet simulation, docs/model/fleet-simulation.md §6).

One client per canton capital (`cap-*` point of data/raw/swiss-grid/grid-10km.csv, T-51).
weight = sum of n_single_family over the 10 km grid cells of that canton
(data/derived/buildings/grid-10km-heat-demand.csv joined on point_id): a labelled population
proxy, not a measured customer distribution. Cantons without any grid cell (Basel-Stadt, 37 km2:
SOURCE.md of the grid) use the single-family building count of their municipalities in
data/derived/buildings/municipality-buildings-heat.csv instead.

Usage: python3 -I scripts/make_fleet_clients.py
"""
import csv
import pathlib
from collections import defaultdict

ROOT = pathlib.Path(__file__).resolve().parent.parent
GRID = ROOT / "data/raw/swiss-grid/grid-10km.csv"
HEAT = ROOT / "data/derived/buildings/grid-10km-heat-demand.csv"
MUNI = ROOT / "data/derived/buildings/municipality-buildings-heat.csv"
OUT = ROOT / "config/fleet/clients/canton-capitals.csv"
CAPITAL_PREFIX = "cap-"
SINGLE_FAMILY_CLASS = "single_family"

HEADER = [
    "# Fleet clients: one per canton capital (cap-* points of data/raw/swiss-grid/grid-10km.csv, T-51).",
    "# weight = sum of n_single_family of the grid cells in the canton (data/derived/buildings/grid-10km-heat-demand.csv):",
    "# a labelled population proxy, not measured customer data. Cantons without a grid cell (BS) use the",
    "# single-family building count of data/derived/buildings/municipality-buildings-heat.csv.",
    "# Generated by scripts/make_fleet_clients.py; do not edit by hand.",
]


def main() -> None:
    with GRID.open(newline="", encoding="utf-8") as f:
        grid = {r["point_id"]: r for r in csv.DictReader(f)}
    weights: dict[str, float] = defaultdict(float)
    with HEAT.open(newline="", encoding="utf-8") as f:
        for r in csv.DictReader(f):
            weights[grid[r["point_id"]]["canton"]] += int(r["n_single_family"])
    muni: dict[str, float] = defaultdict(float)
    with MUNI.open(newline="", encoding="utf-8") as f:
        for r in csv.DictReader(f):
            if r["building_class"] == SINGLE_FAMILY_CLASS:
                muni[r["canton"]] += int(r["n_buildings"])
    rows = []
    for pid, r in sorted(grid.items()):
        if not pid.startswith(CAPITAL_PREFIX):
            continue
        canton = r["canton"]
        weight = weights.get(canton) or muni[canton]
        if weight <= 0:
            raise SystemExit(f"no weight for {pid}")
        rows.append((pid, r["lat_deg"], r["lon_deg"], canton, int(weight)))
    with OUT.open("w", newline="", encoding="utf-8") as f:
        f.write("\n".join(HEADER) + "\n")
        w = csv.writer(f, lineterminator="\n")
        w.writerow(["client_id", "lat_deg", "lon_deg", "canton", "weight"])
        w.writerows(rows)
    print(f"wrote {OUT.relative_to(ROOT)}: {len(rows)} clients")


if __name__ == "__main__":
    main()
